import mermaid from 'https://cdn.jsdelivr.net/npm/mermaid@11/dist/mermaid.esm.min.mjs';

mermaid.initialize({
  startOnLoad: false,
  theme: 'dark',
  themeVariables: {
    darkMode: true,
    background: '#0d1b2d',
    primaryColor: '#12243a',
    primaryTextColor: '#edf5ff',
    primaryBorderColor: '#203750',
    lineColor: '#48d8f2',
    secondaryColor: '#19324b',
    tertiaryColor: '#07111f',
    fontFamily: 'Inter, ui-sans-serif, system-ui, sans-serif',
    fontSize: '13px'
  }
});

async function enhanceDocumentation() {
  // Wrap any bare tables in responsive .table-wrap containers
  document.querySelectorAll('.documentation-content table, .doc-section table').forEach((table) => {
    if (!table.parentElement.classList.contains('table-wrap')) {
      const wrap = document.createElement('div');
      wrap.className = 'table-wrap';
      table.parentNode.insertBefore(wrap, table);
      wrap.appendChild(table);
    }
  });

  // Find all mermaid diagram blocks generated by Kramdown / Rouge or raw markdown
  const codeBlocks = document.querySelectorAll(
    'div.language-mermaid, pre code.language-mermaid, pre.language-mermaid, pre.mermaid'
  );
  if (codeBlocks.length === 0) return;

  for (const block of codeBlocks) {
    const code = block.querySelector('code')?.textContent ?? block.textContent;
    const container = document.createElement('pre');
    container.className = 'mermaid';
    container.textContent = code.trim();

    const wrapper = block.closest('.highlighter-rouge') || block;
    wrapper.replaceWith(container);
  }

  try {
    await mermaid.run();
  } catch (err) {
    console.warn('Mermaid rendering error:', err);
  }
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', enhanceDocumentation);
} else {
  enhanceDocumentation();
}
